function transform(content) {
  let out = content;
  for (const [from, to] of PHRASES) {
    out = out.split(from).join(to);
  }
  out = out.replace(/review-themes\.es/g, "review-themes.sl");
  out = out.replace(/shelf-disambiguation\.sl\.ts/g, "shelf-disambiguation.sl");
  return out;
}

for (const [srcRel, dstRel] of FILE_MAP) {
  const src = path.join(ROOT, srcRel);
  const dst = path.join(ROOT, dstRel);
  if (!fs.existsSync(src)) {
    console.error("Missing:", srcRel);
    continue;
  }
  fs.writeFileSync(dst, transform(fs.readFileSync(src, "utf8")), "utf8");
  console.log("Wrote", dstRel);
}

