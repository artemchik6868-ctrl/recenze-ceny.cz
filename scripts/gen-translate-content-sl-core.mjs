/**
 * One-off: derive translate-content-sl-core.ts from translate-content-es-core.ts
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const src = fs.readFileSync(path.join(root, "scripts/translate-content-es-core.ts"), "utf8");

const ES_MARKERS =
  "const ES_MARKERS = /\\b(España|español|mensajería|contrassegno|corriere|¿|¡| en España|toda España|Productos para la salud|complemento alimenticio|Cómo elegir|Aquí encuentras|Selección curada)\\b/i;";

let t = src
  .replace(
    /LLM translate content\.it \+ niche-content\.it → native content\.es \+ niche-content\.es/,
    "LLM translate content.es + niche-content.es → native content.sl + niche-content.sl (Slovenia)",
  )
  .replace(/from "\.\.\/src\/lib\/content\.it"/g, 'from "../src/lib/content.es"')
  .replace(/from "\.\.\/src\/lib\/niche-content\.it"/g, 'from "../src/lib/niche-content.es"')
  .replace(/NEW_CATEGORY_NAMES_IT/g, "NEW_CATEGORY_NAMES_ES")
  .replace(/buildNicheContentIT/g, "buildNicheContentES")
  .replace(/translate-content-es/g, "translate-content-sl")
  .replace(/function validateEs/g, "function validateSl")
  .replace(/validateEs\(/g, "validateSl(")
  .replace(/const IT_MARKERS =[\s\S]*?;/, ES_MARKERS)
  .replace(/italian marker/g, "spanish marker")
  .replace(/\{ key: string; it: string \}/g, "{ key: string; es: string }")
  .replace(/item\.it/g, "item.es")
  .replace(/, it: /g, ", es: ")
  .replace(/"es": string/g, '"sl": string')
  .replace(/row\.es/g, "row.sl")
  .replace(/const es = raw\[item\.key\]/g, "const sl = raw[item.key]")
  .replace(/if \(!es\)/g, "if (!sl)")
  .replace(/mapped\[item\.key\] = es/g, "mapped[item.key] = sl")
  .replace(/writeContentEs/g, "writeContentSl")
  .replace(/writeNicheEs/g, "writeNicheSl")
  .replace(/content\.es\.ts/g, "content.sl.ts")
  .replace(/niche-content\.es\.ts/g, "niche-content.sl.ts")
  .replace(/category-descriptors\.es/g, "category-descriptors.sl")
  .replace(/buildNicheContentES/g, "buildNicheContentSL")
  .replace(/NEW_CATEGORY_NAMES_ES/g, "NEW_CATEGORY_NAMES_SL")
  .replace(/DELIVERY_ES/g, "DELIVERY_SL")
  .replace(/QUALITY_ES/g, "QUALITY_SL")
  .replace(
    /Spanish content templates for the Spain market\./,
    "Slovenian content templates for the Slovenia market.",
  )
  .replace(
    /Generated by scripts\/translate-content-es\.mjs \(LLM from IT\)\./,
    "Generated by scripts/translate-content-sl.mjs (LLM from ES).",
  )
  .replace(
    /Spanish mirror of niche-content\.it\.ts \(Spain market\)\./,
    "Slovenian mirror of niche-content.es.ts (Slovenia market).",
  )
  .replace(
    /import \{ buildNicheContentES \} from "\.\/niche-content\.es"/,
    'import { buildNicheContentSL } from "./niche-content.sl"',
  )
  .replace(/getCategoryDescriptorES/g, "getCategoryDescriptorSL")
  .replace(/translate-content-es — batches/g, "translate-content-sl — batches")
  .replace(
    /Eres copywriter SEO para un marketplace en España \(mensajería, pago contra reembolso\)\.[\s\S]*?- Longitud similar al original\./,
    `Si copywriter SEO za trgovino na slovenskem trgu (plačilo ob prevzemu, dostava v Sloveniji).
Prevedi vsak španski izvirnik v naravno slovenščino (sl-SI).
PRAVILA:
- Samo slovenščina; brez cirilice; brez španskih besed (España, mensajería, ¿).
- Uporabi «Slovenija», «plačilo ob prevzemu», «dostava v Sloveniji», blagovna znamka «Recenze Ceny».
- OHRANI placeholders: \${b}, \${brand}, \${name}, \${topic}, \${key}, \${lc(name)}.
- Ohrani prelome vrstic \\\\n v seznamih.
- Podobna dolžina kot izvirnik.`,
  )
  .replace(
    /Devuelve JSON: \{ "items": \[{ "key": string, "es": string }, \.\.\.\] \}/,
    'Devuelve JSON: { "items": [{ "key": string, "sl": string }, ...] }',
  )
  .replace(/Categoría salud\/producto:/g, "Kategorija zdravje/proizvod:")
  .replace(
    /Nombres cortos de categorías para marketplace España/,
    "Kratka imena kategorij za trgovino Slovenija",
  )
  .replace(
    /Contenido nicho categoría: \$\{niche\} \(España, pago contra reembolso\)/g,
    "Vsebina niše: ${niche} (Slovenija, plačilo ob prevzemu)",
  )
  .replace(/if \(IT_MARKERS\.test\(es\)\)/g, "if (ES_MARKERS.test(sl))")
  .replace(/if \(ES_MARKERS\.test\(es\)\)/g, "if (ES_MARKERS.test(sl))")
  .replace(/Input \(JSON array de \{key, it\}\):/g, "Input (JSON array de {key, es}):")
  .replace(
    /nameHi: "Productos para la salud"/,
    'nameHi: "Izdelki za zdravje"',
  )
  .replace(/taglineHi: "Selección curada de productos para el bienestar"/, 'taglineHi: "Izbrani izdelki za dobro počutje"')
  .replace(
    /shortDescHi: "Selección curada de productos para la salud con entrega en toda España\./,
    'shortDescHi: "Izbrani izdelki za zdravje z dostavo po vsej Sloveniji.',
  )
  .replace(
    /categoryIntroHi:\s*\n\s*"Selección curada de productos para la salud con entrega en toda España\.",/,
    'categoryIntroHi:\n      "Izbrani izdelki za zdravje z dostavo po vsej Sloveniji.",',
  )
  .replace(/keywordsHi: \["complemento alimenticio salud", "cápsulas naturales España"\]/, 'keywordsHi: ["prehransko dopolnilo zdravje", "naravne kapsule Slovenija"]')
  .replace(/subtitleHi: \(b\) => `\$\{b\} — complemento natural`/g, "subtitleHi: (b) => `${b} — naravno dopolnilo`")
  .replace(
    /productIntro: \(b\) =>\s*\n\s*`\$\{b\} — complemento natural que apoya tu bienestar diario\.`,/,
    "productIntro: (b) =>\n      `${b} — naravno dopolnilo, ki podpira vaše vsakodnevno počutje.`,",
  )
  .replace(/`\$\{lc\(name\)\} españa`/g, "`${lc(name)} slovenija`")
  .replace(/`\$\{lc\(name\)\} comprar`/g, "`${lc(name)} kupiti`")
  .replace(/`\$\{lc\(name\)\} precio`/g, "`${lc(name)} cena`")
  .replace(/`\$\{lc\(name\)\} entrega`/g, "`${lc(name)} dostava`")
  .replace(/return \{ heading: `Cómo elegir «\$\{lc\(name\)\}»`, body \};/, "return { heading: `Kako izbrati «${lc(name)}»`, body };")
  .replace(/body: `Aquí encuentras \$\{topic\}\. \$\{closing\}`/g, "body: `Tukaj najdete ${topic}. ${closing}`");

// Fix validateSl parameter names
t = t.replace(
  /function validateSl\(key: string, it: string, es: string\)/,
  "function validateSl(key: string, esSrc: string, sl: string)",
);
t = t.replace(/if \(!es\?\.trim\(\)\)/g, "if (!sl?.trim())");
t = t.replace(/if \(CYRILLIC\.test\(es\)\)/g, "if (CYRILLIC.test(sl))");
t = t.replace(/if \(it\.includes\(ph\) && !es\.includes\(ph\)\)/g, "if (esSrc.includes(ph) && !sl.includes(ph))");
t = t.replace(/if \(it\.includes\(BRAND\)/g, "if (esSrc.includes(BRAND)");
t = t.replace(/!es\.includes\("\$\{b\}"\)/g, '!sl.includes("${b}")');
t = t.replace(/if \(it\.includes\(NAME\) && !es\.includes\("\$\{name\}"\)\)/g, 'if (esSrc.includes(NAME) && !sl.includes("${name}"))');

fs.writeFileSync(path.join(root, "scripts/translate-content-sl-core.ts"), t);
console.log("Wrote scripts/translate-content-sl-core.ts", t.length, "bytes");
